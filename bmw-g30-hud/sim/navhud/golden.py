def _case(label: str, ev: NavEvent) -> Dict:
    return {
        "label": label,
        "event": ev.to_dict(),
        "frames": {p.name: Translator(p).translate(ev).to_dict() for p in PROFILES},
    }


def build_golden() -> Dict:
    cases = []
    for name in sorted(scenarios.SCENARIOS):
        for ev in scenarios.SCENARIOS[name]():
            cases.append(_case(f"{name}#{ev.event_id}", ev))
    for label, ev in edge_events():
        cases.append(_case(label, ev))
    return {
        "_comment": (
            "Generated by sim/navhud/golden.py - do not hand-edit. Each case is a "
            "NavEvent and the HudFrame the reference translator produces for each "
            "display profile. The Swift NavHUDKit tests assert byte-equal output."
        ),
        "profiles": [p.name for p in PROFILES],
        "distance_text": [{"meters": m, "text": meters_to_us_text(m)} for m in DISTANCES_M],
        "cases": cases,
    }


def render(golden: Dict) -> str:
    return json.dumps(golden, indent=1, sort_keys=True) + "\n"


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    out = argv[0] if argv else "../test-vectors/hud_golden.json"
    text = render(build_golden())
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
