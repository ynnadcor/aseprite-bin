"""Generate test-vectors/hud_golden.json - translator input/output pairs.

The Swift port (ios-app/BMWLinkKit/Sources/NavHUDKit) asserts against this
file, so the on-phone translator and this Python reference cannot silently
diverge. tests/test_hud_golden.py fails if the committed file is stale.

Regenerate after an intentional translator change:
    cd sim && python -m navhud.golden ../test-vectors/hud_golden.json
"""

from __future__ import annotations

import json
import sys
