from . import scenarios

PROFILES: List[HudProfile] = [G30_HUD_PROFILE, G30_KOMBI_PROFILE]

# Distances chosen to hit every branch and rounding boundary of
# meters_to_us_text (feet <100, feet >=100, the 0.1 mi switch, the 10 mi
